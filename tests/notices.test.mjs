/**
 * generate-notices.mjs 纯函数直测：license 字段归一、repository URL 清洗、
 * 许可文本去重与 Markdown 组装。不触发 cargo/node_modules 实际扫描。
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { normalizeLicenseField, repoUrlOf, dedupeTexts, renderMarkdown } from '../scripts/generate-notices.mjs';

test('license 字段三种历史形态归一为表达式字符串', () => {
  assert.equal(normalizeLicenseField('MIT'), 'MIT');
  assert.equal(normalizeLicenseField(' (MIT OR Apache-2.0) '), '(MIT OR Apache-2.0)');
  assert.equal(normalizeLicenseField([{ type: 'MIT' }, { type: 'ISC' }]), 'MIT OR ISC');
  assert.equal(normalizeLicenseField(['MIT', 'MIT']), 'MIT', '重复表达式去重');
  assert.equal(normalizeLicenseField({ type: 'Apache-2.0' }), 'Apache-2.0');
  assert.equal(normalizeLicenseField(undefined), 'Unknown');
  assert.equal(normalizeLicenseField(null), 'Unknown');
  assert.equal(normalizeLicenseField('   '), 'Unknown');
});

test('repository 字段归一成 https URL，回退 homepage', () => {
  assert.equal(repoUrlOf({ repository: 'git+https://github.com/a/b.git' }), 'https://github.com/a/b');
  assert.equal(repoUrlOf({ repository: { url: 'git://github.com/a/b.git' } }), 'https://github.com/a/b');
  assert.equal(repoUrlOf({ repository: { url: 'ssh://git@github.com/a/b.git' } }), 'https://github.com/a/b');
  assert.equal(repoUrlOf({ repository: 'a/b', homepage: 'https://example.invalid' }), 'https://github.com/a/b', '短缩写补全为 GitHub URL');
  assert.equal(repoUrlOf({ homepage: 'https://example.invalid' }), 'https://example.invalid');
  assert.equal(repoUrlOf({}), '');
  assert.equal(repoUrlOf({ repository: 'not a url' }), 'not a url', '无法识别时原样保留');
});

test('相同文本跨包去重，用户列表合并；不同文本分开', () => {
  const textA = 'MIT License\n\nCopyright (c) 2026 Someone\n';
  const textB = 'Apache License\nVersion 2.0\n';
  const entries = dedupeTexts([
    { name: 'pkg-a', version: '1.0.0', license: 'MIT', texts: [{ hash: 'a'.repeat(64), text: textA, file: 'LICENSE' }] },
    { name: 'pkg-b', version: '2.1.0', license: 'MIT', texts: [{ hash: 'a'.repeat(64), text: textA, file: 'LICENSE' }] },
    { name: 'pkg-c', version: '3.0.0', license: 'Apache-2.0', texts: [{ hash: 'b'.repeat(64), text: textB, file: 'LICENSE-APACHE' }] },
  ]);
  assert.equal(entries.length, 2);
  const mit = entries.find(entry => entry.license === 'MIT');
  assert.deepEqual(mit.users, ['pkg-a@1.0.0', 'pkg-b@2.1.0']);
  assert.equal(mit.text, textA);
});

test('renderMarkdown 组装双清单、文本附录与缺文本说明', () => {
  const text = 'MIT License\n\nCopyright (c) 2026 Holder\n';
  const npm = [
    { name: 'zlib-ish', version: '2.0.0', license: 'Zlib', url: 'https://example.invalid/z', texts: [] },
    { name: 'alpha-pkg', version: '1.0.0', license: 'MIT', url: 'https://example.invalid/a', texts: [{ hash: 'c'.repeat(64), text, file: 'LICENSE' }] },
  ];
  const cargo = [
    { name: 'serde', version: '1.0.228', license: 'MIT OR Apache-2.0', url: 'https://github.com/serde-rs/serde', texts: [] },
  ];
  const markdown = renderMarkdown({ npm, cargo, generatedAt: '2026-10-31T00:00:00.000Z' });
  assert.match(markdown, /## npm dependencies/);
  assert.match(markdown, /Total: 2/);
  assert.match(markdown, /## Cargo dependencies/);
  assert.match(markdown, /Total: 1/);
  // 表格按包名排序：alpha 在 zlib 前
  assert.ok(markdown.indexOf('| [alpha-pkg]') < markdown.indexOf('| [zlib-ish]'));
  // 文本附录带使用方折叠
  assert.match(markdown, /### MIT \(text c{12}\)/);
  assert.match(markdown, /Used by 1 package\(s\): alpha-pkg@1.0.0/);
  assert.match(markdown, /```text/);
  // 缺文本的包列入说明节，链接保留
  assert.match(markdown, /## Licenses without a bundled text/);
  assert.match(markdown, /- serde@1\.0\.228 \(MIT OR Apache-2\.0\) — https:\/\/github\.com\/serde-rs\/serde/);
  assert.match(markdown, /- zlib-ish@2\.0\.0 \(Zlib\)/);
  // 生成时间戳写入，标记非手编文件
  assert.match(markdown, /Generated by `scripts\/generate-notices\.mjs` at 2026-10-31T00:00:00\.000Z/);
});
